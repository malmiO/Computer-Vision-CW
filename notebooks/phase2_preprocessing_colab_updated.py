"""Checks whether a photo is good enough to grade reliably, while making sure the quality filter does not unfairly reject images from any disease grade."""

def fit_quality_thresholds(metrics: pd.DataFrame, pct: float = 1.0):
    """Data-driven thresholds: an image is flagged if it is worse than the
    `pct`-th percentile of the TRAINING set on any metric (or brighter than the
    100-pct percentile for over-exposure). Using percentiles avoids hand-picked
    magic numbers and adapts to whichever dataset is used.

    fov_ratio is deliberately NOT used: on APTOS its lowest values belong to
    well-framed photos from one camera whose circle has a small notch, so a
    fov_ratio threshold rejected a camera type rather than bad framing
    (phase 2 evidence, decision D20)."""
    return {
        "sharpness_min": float(np.percentile(metrics["sharpness"], pct)),
        "brightness_min": float(np.percentile(metrics["brightness"], pct)),
        "brightness_max": float(np.percentile(metrics["brightness"], 100 - pct)),
        "contrast_min": float(np.percentile(metrics["contrast"], pct)),
    }

