def optic_disc_centre(img):
    """The optic disc is the brightest LARGE bright region. Blurring with a width
    close to the disc radius averages away small bright lesions (exudates), so the
    brightest point of the blurred lightness image is the disc centre."""
    light = cv2.cvtColor(img, cv2.COLOR_RGB2LAB)[..., 0].astype(np.float32)
    light[img.max(2) <= 10] = 0
    blurred = cv2.GaussianBlur(light, (0, 0), img.shape[0] / 14)
    return np.unravel_index(np.argmax(blurred), blurred.shape)

def detail_patch(img, win=70):
    """Top-left corner of the window with the most edge energy, away from the optic disc."""
    green = img[..., 1].astype(np.float32)
    energy = cv2.boxFilter(np.abs(cv2.Laplacian(green, cv2.CV_32F)), -1, (win, win), normalize=False)
    dy, dx = optic_disc_centre(img)
    yy, xx = np.mgrid[:img.shape[0], :img.shape[1]]
    near_disc = (yy - dy) ** 2 + (xx - dx) ** 2 < (img.shape[0] / 14 + win / 2 + 5) ** 2
    inside = cv2.erode((img.max(2) > 10).astype(np.uint8), np.ones((win, win), np.uint8))
    energy[near_disc | (inside == 0)] = 0
    cy, cx = np.unravel_index(np.argmax(energy), energy.shape)
    return max(cy - win // 2, 0), max(cx - win // 2, 0)

