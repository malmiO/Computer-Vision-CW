"""runs each experiment using two-stage transfer learning, first training the new model head and then carefully fine-tuning part of the pretrained model, while using validation QWK and confidence intervals to compare the runs fairly."""

def done_runs():
    return set(pd.read_csv(EXP_CSV).run_name) if EXP_CSV.exists() else set()

def run(name, **overrides):
    """Train one configuration with src/train.py, unless it already finished (resumable)."""
    if name in done_runs():
        print(f"✓ {name} already done - skipped"); return
    args = {"backbone": "efficientnet_b0", "variant": VARIANT, "aug": AUG, "balance": BALANCE,
            "epochs_head": EPOCHS_HEAD, "epochs_ft": EPOCHS_FT, **overrides}
    flags = " ".join(f"--{k} {v}" for k, v in args.items())
    print(f"▶ {name}: {flags}")
    t0 = time.time()
    get_ipython().system(f"cd {SRC} && python train.py {flags} --mixed_precision --run_name {name} {EXTRA_ARGS} 2>&1 | grep -v -E 'oneDNN|cuda_|absl|computation placer|TF-TRT|cpu_feature'")
    if name in done_runs():
        print(f"  finished in {(time.time() - t0) / 60:.1f} min")
    else:
        print(f"  ⚠ {name} did not finish - scroll up for the error message")

def results(prefix):
    exp = pd.read_csv(EXP_CSV)
    return exp[exp.run_name.str.startswith(prefix)].drop_duplicates("run_name", keep="last").reset_index(drop=True)

