"""Hyperparameter tuning"""

def choose(stage, key, default):
    """Highest QWK wins, but the default is kept unless beaten by at least NOISE."""
    top = stage.sort_values("val_qwk", ascending=False).iloc[0]
    base = stage[stage[key] == default].iloc[0]
    return float(top[key]) if top.val_qwk - base.val_qwk >= NOISE else float(default)

# The benchmark B0 run (lr 1e-4, unfreeze 0.3, dropout 0.4) is the shared starting point
b0 = results("bench_efficientnet_b0")
assert len(b0), "Run step 4 first"

# Stage 1 - fine-tuning learning rate
for lr in [3e-5, 3e-4]:
    run(f"tune_lr_{lr:g}", lr_ft=lr)
stage1 = pd.concat([b0, results("tune_lr_")], ignore_index=True)
LR = choose(stage1, "lr_ft", 1e-4)
print("→ fine-tuning learning rate:", LR)

# Stage 2 - unfreezing depth, at the chosen learning rate
for uf in [0.6, 1.0]:
    run(f"tune_unfreeze_{uf:g}_lr_{LR:g}", lr_ft=LR, unfreeze=uf)
stage2 = pd.concat([stage1[np.isclose(stage1.lr_ft, LR)], results(f"tune_unfreeze_")
                    .query("lr_ft == @LR")], ignore_index=True)
UF = choose(stage2, "unfreeze", 0.3)
print("→ unfreeze fraction:", UF)

# Stage 3 - dropout, at the chosen learning rate and unfreezing
for dp in [0.2, 0.6]:
    run(f"tune_dropout_{dp:g}_uf_{UF:g}_lr_{LR:g}", lr_ft=LR, unfreeze=UF, dropout=dp)
stage3 = pd.concat([stage2[np.isclose(stage2.unfreeze, UF)], results("tune_dropout_")
                    .query("lr_ft == @LR and unfreeze == @UF")], ignore_index=True)
DROPOUT = choose(stage3, "dropout", 0.4)
print("→ dropout:", DROPOUT)

"""Tuning results"""

tuning = pd.concat([stage1.assign(stage="1 learning rate"), stage2.assign(stage="2 unfreeze"),
                    stage3.assign(stage="3 dropout")])
keep = ["stage", "run_name", "lr_ft", "unfreeze", "dropout", "val_qwk", "val_qwk_ci_low", "val_qwk_ci_high",
        "val_macro_f1", "train_val_acc_gap", "best_epoch"]
tuning = tuning[keep].reset_index(drop=True)
tuning.to_csv(config.OUTPUT_DIR / "tuning_results.csv", index=False)
