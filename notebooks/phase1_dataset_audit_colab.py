def index_from_csv(csv_path, image_dir):
    df = pd.read_csv(csv_path)
    id_col = "id_code" if "id_code" in df else df.columns[0]
    label_col = "diagnosis" if "diagnosis" in df else df.columns[1]
    files = {p.stem: p for p in image_dir.iterdir() if p.suffix.lower() in IMG_EXT}
    df["path"] = df[id_col].astype(str).map(lambda s: str(files.get(s, "")))
    missing = int((df["path"] == "").sum())
    if missing: print(f"WARNING: {missing} CSV rows have no image file")
    df = df[df["path"] != ""]
    return pd.DataFrame({"id": df[id_col].astype(str), "path": df["path"],
                         "grade": df[label_col].astype(int)})

def index_from_folders(root):
    rows = [{"id": p.stem, "path": str(p), "grade": FOLDER_NAME_TO_GRADE[p.parent.name.strip().lower()]}
            for p in Path(root).rglob("*")
            if p.suffix.lower() in IMG_EXT and p.parent.name.strip().lower() in FOLDER_NAME_TO_GRADE]
    if not rows: raise RuntimeError("No class folders recognised - extend FOLDER_NAME_TO_GRADE")
    return pd.DataFrame(rows)

