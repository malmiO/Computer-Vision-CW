def stratified_split(df):
    rest, test = train_test_split(df, test_size=TEST_FRACTION, stratify=df["grade"], random_state=SEED)
    train, val = train_test_split(rest, test_size=VAL_FRACTION/(1-TEST_FRACTION),
                                  stratify=rest["grade"], random_state=SEED)
    return pd.concat([train.assign(split="train"), val.assign(split="val"),
                      test.assign(split="test")]).reset_index(drop=True)

