"""Duplicates and data leakage"""

def duplicate_groups(bits, max_dist):
    n = len(bits); parent = np.arange(n)
    def find(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]; i = parent[i]
        return i
    for start in range(0, n, 2048):                       # chunked to bound memory
        block = bits[start:start+2048]
        same = block @ bits.T + (1-block) @ (1-bits).T    # matching ones + matching zeros
        bi, bj = np.where(bits.shape[1] - same <= max_dist)
        bi = bi + start; keep = bj > bi
        for i, j in zip(bi[keep], bj[keep]):
            ri, rj = find(int(i)), find(int(j))
            if ri != rj: parent[rj] = ri
    return np.array([find(i) for i in range(n)])

def plot_duplicates(dups, out=FIG_DIR / "duplicates.png", max_groups=4):
    groups = [g for _, g in dups.groupby("dup_group")][:max_groups]
    if not groups:
        print("No duplicate pairs found."); return
    fig, axes = plt.subplots(len(groups), 2, figsize=(6, 3*len(groups)), squeeze=False)
    for r, g in enumerate(groups):
        for c in range(2):
            axes[r, c].axis("off")
            if c < len(g):
                row = g.iloc[c]
                axes[r, c].imshow(Image.open(row["path"]).convert("RGB").resize((256, 256)))
                axes[r, c].set_title(f"{row['id'][:12]}  grade={row['grade']}", fontsize=9)
    fig.suptitle("Near-duplicate pairs found by perceptual hashing")
    fig.tight_layout(); fig.savefig(out, dpi=150); plt.show()

