def load_rgb(path):
    bgr = cv2.imread(str(path), cv2.IMREAD_COLOR)
    if bgr is None: raise FileNotFoundError(path)
    return cv2.cvtColor(bgr, cv2.COLOR_BGR2RGB)

def fov_mask(img, tol=10):
    gray = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)
    return cv2.morphologyEx((gray > tol).astype(np.uint8), cv2.MORPH_OPEN, np.ones((5,5), np.uint8))

def crop_fov(img, tol=10):
    m = fov_mask(img, tol); ys, xs = np.where(m > 0)
    if len(xs) < 0.05 * m.size: return img
    return img[ys.min():ys.max()+1, xs.min():xs.max()+1]

def quality_metrics(img):
    small = cv2.resize(crop_fov(img), (512, 512), interpolation=cv2.INTER_AREA)
    mask = fov_mask(small).astype(bool)
    if mask.sum() < 100:
        return {"sharpness":0.0, "brightness":0.0, "contrast":0.0, "fov_ratio":0.0}
    green = small[..., 1]
    hsv = cv2.cvtColor(small, cv2.COLOR_RGB2HSV)
    return {"sharpness": float(cv2.Laplacian(green, cv2.CV_64F)[mask].var()),
            "brightness": float(hsv[..., 2][mask].mean()),
            "contrast": float(green[mask].std()),
            "fov_ratio": float(mask.mean())}

def phash_bits(gray):
    """64-bit perceptual hash: shrink to 32x32, DCT, keep the top-left 8x8 block
    (coarse structure), bit = coefficient above the block median."""
    small = cv2.resize(gray, (32, 32), interpolation=cv2.INTER_AREA).astype(np.float32)
    low = cv2.dct(small)[:8, :8]
    return (low > np.median(low)).flatten().astype(np.float32)

def audit_one(path):
    rgb = load_rgb(path); h, w = rgb.shape[:2]
    green = cv2.createCLAHE(2.0, (8, 8)).apply(crop_fov(rgb)[..., 1])
    return {"path": path, "width": w, "height": h, **quality_metrics(rgb), "bits": phash_bits(green)}

