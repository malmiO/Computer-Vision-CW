def done_runs():
    return set(pd.read_csv(EXP_CSV).run_name) if EXP_CSV.exists() else set()

def run(name, **overrides):
    """Train one configuration with src/train.py, unless it already finished (resumable)."""
    if name in done_runs():
        print(f"✓ {name} already done - skipped"); return
    args = {**STABLE, "epochs_head": EPOCHS_HEAD, "epochs_ft": EPOCHS_FT, **overrides}
    flags = " ".join(f"--{k} {v}" for k, v in args.items())
    print(f"▶ {name}: {flags}")
    t0 = time.time()
    get_ipython().system(f"cd {SRC} && python train.py {flags} --mixed_precision --run_name {name} {EXTRA_ARGS} 2>&1 | grep -v -E 'oneDNN|cuda_|absl|computation placer|TF-TRT|cpu_feature'")
    print(f"  finished in {(time.time() - t0) / 60:.1f} min" if name in done_runs()
          else f"  ⚠ {name} did not finish - scroll up for the error message")

def pick(table, column, default, metric="val_qwk"):
    """Best value wins only if it beats the default by at least NOISE (the phase 4 rule)."""
    top = table.sort_values(metric, ascending=False).iloc[0]
    base = table[table[column] == default].iloc[0]
    return top[column] if top[metric] - base[metric] >= NOISE else default

