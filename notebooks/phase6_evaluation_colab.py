"""bench_densenet121 was selected because it achieved better validation performance and showed less overfitting than the final run"""

# Commented out IPython magic to ensure Python compatibility.
# %matplotlib inline
import json, time
import numpy as np, pandas as pd
import matplotlib.pyplot as plt
from IPython.display import Image, display
import config
import evaluate as ev

MODEL_RUN = "bench_densenet121"
def show(path, width=1000):
    """Display a saved figure (the PNG in Drive is the copy to use in the report)."""
    print("saved:", Path(path).relative_to(PROJECT_DIR)); display(Image(str(path), width=width))

model, meta = ev.load_run(MODEL_RUN)
val_df, test_df = ev.eval_splits(meta)
y_val, y = val_df.grade.values, test_df.grade.values
ev.EVAL_DIR.mkdir(parents=True, exist_ok=True)
print(f"{MODEL_RUN}: {meta['backbone']}, {meta['variant']}, input {meta['size']}px, "
      f"validation QWK {meta['val_qwk']}")
print(f"validation images: {len(val_df)} | test images: {len(test_df)}",
      "| test grades:", np.bincount(y, minlength=5).tolist())

"""Accuracy and loss curves"""

show(ev.plot_training_curves(MODEL_RUN, meta.get("epochs_head", 3)))

"""Predictions"""

t0 = time.time()
pv, rv, _ = ev.predict(model, val_df, meta["size"], tta=True)
print(f"validation done in {(time.time() - t0) / 60:.1f} min")
settings = ev.fit_on_validation(pv, rv, y_val)
print(json.dumps(settings, indent=2))

t0 = time.time()
pt, rt, spread = ev.predict(model, test_df, meta["size"], tta=True)
pt_plain, rt_plain, _ = ev.predict(model, test_df, meta["size"], tta=False)
print(f"test done in {(time.time() - t0) / 60:.1f} min")
pcal = ev.temperature_scale(pt, settings["temperature"])
pred = pcal.argmax(1)
pd.DataFrame({"id": test_df.id, "grade": y, "pred": pred, "confidence": pcal.max(1), "tta_spread": spread,
              "referable_prob": rt, **{f"p{c}": pcal[:, c] for c in range(5)}}
             ).to_csv(ev.EVAL_DIR / "test_predictions.csv", index=False)

"""Headline results"""

metrics = ev.core_metrics(y, pcal, rt, settings)
plain = {"accuracy": round(float((pt_plain.argmax(1) == y).mean()), 4), "qwk": round(ev.qwk(y, pt_plain.argmax(1)), 4)}
rows = [
    ("Accuracy (5 grades)", metrics["accuracy"], metrics["accuracy_ci"]),
    ("Quadratic weighted kappa (QWK)", metrics["qwk"], metrics["qwk_ci"]),
    ("Macro-F1 (all grades weighted equally)", metrics["macro_f1"], metrics["macro_f1_ci"]),
    ("Weighted-F1", metrics["weighted_f1"], None),
    ("Referable DR: AUC", metrics["referable_auc"], None),
    ("Referable DR: sensitivity", metrics["referable_sensitivity"], None),
    ("Referable DR: specificity", metrics["referable_specificity"], None),
    ("Any DR vs No DR: AUC", metrics["any_dr_auc"], None),
    ("QWK with ordinal decoding", metrics["ordinal_decoding_qwk"], None),
    ("QWK without test-time augmentation", plain["qwk"], None),
    ("Accuracy without test-time augmentation", plain["accuracy"], None),
]
headline = pd.DataFrame([{"metric": m, "value": v, "95% CI": f"{c[0]:.3f} – {c[1]:.3f}" if c else ""}
                         for m, v, c in rows])
headline.to_csv(ev.EVAL_DIR / "headline_metrics.csv", index=False)
display(headline)
print(f"Validation QWK was {meta['val_qwk']}; test QWK is {metrics['qwk']} - "
      + ("consistent (inside the test interval)." if metrics["qwk_ci"][0] <= meta["val_qwk"] <= metrics["qwk_ci"][1]
         else "outside the test interval - discuss why in the report."))

"""Precision, recall and F1 per grade"""

table = ev.classification_table(y, pred)
table.to_csv(ev.EVAL_DIR / "classification_report.csv")
display(table)
show(ev.plot_per_class(table), width=800)

"""Confusion matrix"""

show(ev.plot_confusion(y, pred))
cm = pd.crosstab(pd.Series(y, name="true"), pd.Series(pred, name="predicted"))
far = int(sum(cm.loc[i, j] for i in cm.index for j in cm.columns if abs(i - j) >= 2))
print(f"Errors one grade away: {int((np.abs(y - pred) == 1).sum())} | two or more grades away: {far} "
      f"| referable cases called No DR: {int(((y >= 2) & (pred == 0)).sum())}")

"""Screening performance and ROC curves"""

show(ev.plot_roc(y, pcal, rt, settings))
print(f"Referable DR on the test set: sensitivity {metrics['referable_sensitivity']:.1%}, "
      f"specificity {metrics['referable_specificity']:.1%} (target sensitivity 87%, set on validation)")

"""Calibration"""

path, ece_before, ece_after = ev.plot_reliability(pt, pcal, y)
metrics["ece_before"], metrics["ece_after"] = round(ece_before, 4), round(ece_after, 4)
show(path, width=520)
print(f"ECE before {ece_before:.3f} -> after temperature scaling {ece_after:.3f} (T = {settings['temperature']:.2f})")

"""Error analysis with Grad-CAM"""

correct = [int(np.where((pred == g) & (y == g))[0][np.argmax(pcal[(pred == g) & (y == g), g])])
           for g in range(5) if ((pred == g) & (y == g)).any()]
if correct:
    show(ev.gradcam_panel(model, meta, test_df, correct, pcal, y, "eval_gradcam_correct.png",
                          "Correct predictions, one per grade: input (top) and Grad-CAM (bottom)"))
print("grades with a correct example:", [int(y[i]) for i in correct])
wrong = np.where(pred != y)[0]
worst = wrong[np.argsort(-pcal[wrong].max(1))][:6]
if len(worst):
    show(ev.gradcam_panel(model, meta, test_df, worst, pcal, y, "eval_gradcam_errors.png",
                          "Most confident mistakes: input (top) and Grad-CAM of the predicted grade (bottom)"))

"""Does the model rely on the camera?"""

q = pd.read_csv(OUTPUT_DIR / "image_quality.csv")[["id", "width", "height", "sharpness", "brightness", "contrast"]]
q["camera"] = q.width.astype(str) + "x" + q.height.astype(str)
splits_all = pd.read_csv(OUTPUT_DIR / "splits.csv")[["id", "grade", "split"]].merge(q, on="id")
tr = splits_all[splits_all.split == "train"]
test_q = test_df[["id"]].merge(q, on="id", how="left")

baseline = ev.camera_only_baseline(tr.camera, tr.grade.values, test_q.camera, y)
print(f"QWK of the model: {metrics['qwk']:.3f} | QWK of the camera-only rule: {baseline:.3f}")
cams = ev.group_table(y, pred, test_q.camera)
cams.to_csv(ev.EVAL_DIR / "per_camera.csv", index=False)
display(cams)
mixed = cams[(cams.no_dr_share > 0.2) & (cams.no_dr_share < 0.8)]
print("Mixed camera groups (camera cannot reveal the grade):",
      ", ".join(f"{r.group}: QWK {r.qwk}" for r in mixed.itertuples()) or "none with enough test images")

"""Performance by image quality"""

test_q["sharpness_third"] = pd.qcut(test_q.sharpness, 3, labels=["least sharp", "middle", "sharpest"])
by_sharp = ev.group_table(y, pred, test_q.sharpness_third.astype(str), min_n=5)
display(by_sharp)

thr = json.load(open(OUTPUT_DIR / "quality_thresholds.json"))
refused = ((test_q.sharpness < thr["sharpness_min"]) | (test_q.brightness < thr["brightness_min"])
           | (test_q.contrast < thr["contrast_min"]))
by_gate = ev.group_table(y, pred, refused.map({True: "gate would refuse", False: "gate accepts"}), min_n=1)
display(by_gate)
pd.concat([by_sharp.assign(split_by="sharpness"), by_gate.assign(split_by="quality gate")]).to_csv(
    ev.EVAL_DIR / "per_quality.csv", index=False)

""" Human in the loop: deferring uncertain cases"""

sel = ev.selective_prediction(y, pcal, spread)
sel.to_csv(ev.EVAL_DIR / "selective_prediction.csv", index=False)
flag = pcal.max(1) < settings["review_confidence"]
show(ev.plot_selective(sel, 1 - flag.mean()))
display(sel.pivot(index="coverage", columns="uncertainty", values=["accuracy", "qwk"]).sort_index(ascending=False))
print(f"App review rule on the test set: {flag.mean():.1%} flagged | accuracy on flagged {(pred[flag] == y[flag]).mean():.1%} "
      f"vs on the rest {(pred[~flag] == y[~flag]).mean():.1%}")

"""Synthetic stress test "DR-C"
"""

import robustness as rb
thr = json.load(open(OUTPUT_DIR / "quality_thresholds.json"))
meta_cal = {**meta, "temperature": settings["temperature"]}
show(rb.plot_examples(), width=1100)
t0 = time.time()
robust = rb.run_robustness(model, meta_cal, thr, n=200)
robust.to_csv(ev.EVAL_DIR / "robustness.csv", index=False)
print(f"done in {(time.time() - t0) / 60:.1f} min")
show(rb.plot_robustness(robust))
display(robust)

"""checking does blur alone make the model see disease?"""

probe = rb.blur_probe(model, meta_cal, n=100)
probe.to_csv(ev.EVAL_DIR / "blur_probe.csv", index=False)
display(probe)
show(rb.plot_blur_probe(probe), width=700)

